Num = int(input("Enter a number: "))
Num2 = int(input("Enter a 2nd number: "))
Num3 = int(input("Enter a 3rd number: "))

print("Sum: " + str(Num + Num2 + Num3))
print("Difference: " + str(Num - Num2 - Num3))
print("Product: " + str(Num * Num2 * Num3))
print("Division: " + str(Num / Num2 / Num3))
print("Floor Division: " + str((Num // Num2 // Num3) ))
print("Modulus: " + str(Num % Num2 % Num3))
